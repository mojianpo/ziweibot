/**
 * 把一个宫位写法归一到标准名。认不出来返回 null（= 不认识的宫位写法）。
 */
export function canonicalPalaceName(raw: string): string | null {
  const name = raw.trim();
  if (!name) return null;
  if (PALACE_NAMES.includes(name)) return name;
  if (PALACE_SYNONYMS[name]) return PALACE_SYNONYMS[name];

  // 去掉「宫」后缀再试
  if (name.length > 1 && name.endsWith('宫')) {
    const stem = name.slice(0, -1);
    const direct = PALACE_SYNONYMS[stem + '宫'] ?? PALACE_SYNONYMS[stem];
    if (direct) return direct;
    if (PALACE_NAMES.includes(stem)) return stem;
    // 容忍前缀
    for (const p of PALACE_PREFIXES) {
      if (stem.startsWith(p) && stem.length > 1) {
        const rest = stem.slice(p.length);
        const viaPrefix = PALACE_SYNONYMS[rest + '宫'] ?? PALACE_SYNONYMS[rest];
        if (viaPrefix) return viaPrefix;
        if (PALACE_NAMES.includes(rest)) return rest;
      }
    }
  }
  return null;
}
